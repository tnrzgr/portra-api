@app.get("/fiyat/{market}/{symbol}")
def get_fiyat(market: str, symbol: str):
    try:
        if market == "BIST":
            res = requests.get("https://api.collectapi.com/economy/hisseSenedi", headers={
                "content-type": "application/json",
                "authorization": f"apikey {COLLECT_API_KEY}"
            })
            data = res.json()
            if data.get("success"):
                for s in data["result"]:
                    if s["code"] == symbol:
                        return {"price": float(s["lastprice"])}
        elif market == "ABD":
            res = requests.get(f"https://api.twelvedata.com/price?symbol={symbol}&apikey={TWELVE_DATA_API_KEY}")
            data = res.json()
            if "price" in data:
                return {"price": float(data["price"])}
        elif market == "Kripto":
            res = requests.get(f"https://api.twelvedata.com/price?symbol={symbol}/USD&apikey={TWELVE_DATA_API_KEY}")
            data = res.json()
            if "price" in data:
                return {"price": float(data["price"])}
        elif market == "Emtia":
            res = requests.get(f"https://api.twelvedata.com/price?symbol={symbol}/USD&apikey={TWELVE_DATA_API_KEY}")
            data = res.json()
            if "price" in data:
                return {"price": float(data["price"])}
        elif market == "Döviz":
            res = requests.get("https://api.collectapi.com/economy/currency", headers={
                "content-type": "application/json",
                "authorization": f"apikey {COLLECT_API_KEY}"
            })
            data = res.json()
            if data.get("success"):
                for c in data["result"]:
                    if c["code"] == symbol:
                        return {"price": float(c["rate"])}
        elif market == "Fon":
            from tefasmak import fon_anlik_bilgi
            info = fon_anlik_bilgi(symbol.upper())
            if info and "sonFiyat" in info:
                return {"price": float(info["sonFiyat"])}
        return {"price": None}
    except Exception as e:
        return {"price": None}

